// Generate translation files
function generateTranslationFiles() {
  console.log('🌍 Generating translation files...');

  for (const lang of languages) {
    for (const namespace of namespaces) {
      const dir = path.join(process.cwd(), 'public', 'locales', lang);
      const filePath = path.join(dir, `${namespace}.json`);

      // Create directory if it doesn't exist
      if (!fs.existsSync(dir)) {
        fs.mkdirSync(dir, { recursive: true });
      }

      // Get translations for this language and namespace
      let translations;
      if (namespace === 'users') {
        translations = usersTranslations[lang as keyof typeof usersTranslations];
      } else if (namespace === 'settings') {
        translations = settingsTranslations[lang as keyof typeof settingsTranslations];
      }

      if (translations) {
        // Write translation file
        fs.writeFileSync(filePath, JSON.stringify(translations, null, 2));
        console.log(`✅ Created ${filePath}`);
      }
    }
  }

  console.log('🎉 Translation files generated successfully!');
}

